-- Physical shop-tank measurement baseline and post-measurement live balance.
create table if not exists public.water_tank_measurements (
  id bigint generated by default as identity primary key,
  tank_code text not null default 'shop_counter' check (tank_code = 'shop_counter'),
  measured_at timestamptz not null default now(),
  measured_litres numeric(14,2) not null check (measured_litres >= 0),
  ledger_litres numeric(14,2) not null check (ledger_litres >= 0),
  variance_litres numeric(14,2) generated always as (measured_litres - ledger_litres) stored,
  measurement_method text not null default 'owner_reported'
    check (measurement_method in ('owner_reported','manual_gauge','sensor')),
  note text not null,
  entered_by uuid references auth.users(id),
  request_id uuid not null default gen_random_uuid() unique,
  created_at timestamptz not null default now()
);

alter table public.water_tank_measurements
  add column if not exists request_id uuid not null default gen_random_uuid();

create unique index if not exists water_tank_measurements_request_id_uidx
  on public.water_tank_measurements(request_id);

alter table public.water_tank_measurements enable row level security;
revoke all on public.water_tank_measurements from anon, authenticated;
grant select, insert on public.water_tank_measurements to authenticated;
grant usage, select on sequence public.water_tank_measurements_id_seq to authenticated;

drop policy if exists "Admins read water tank measurements" on public.water_tank_measurements;
create policy "Admins read water tank measurements"
  on public.water_tank_measurements for select to authenticated
  using ((select is_admin()));

drop policy if exists "Admins insert water tank measurements" on public.water_tank_measurements;
create policy "Admins insert water tank measurements"
  on public.water_tank_measurements for insert to authenticated
  with check ((select is_admin()));

drop trigger if exists audit_trigger on public.water_tank_measurements;
create trigger audit_trigger
  after insert or update or delete on public.water_tank_measurements
  for each row execute function log_changes();

