create or replace view public.shop_water_tank_current_balance
with (security_invoker = true) as
with latest as (
  select m.*
  from public.water_tank_measurements m
  where m.tank_code = 'shop_counter'
  order by m.measured_at desc, m.id desc
  limit 1
),
flows as (
  select
    coalesce((
      select sum(t.tanker_count * 1000)
      from public.water_tanker_purchases t cross join latest l
      where t.water_use = 'shop_counter' and t.created_at > l.measured_at
    ), 0) as inflow_litres,
    coalesce((
      select sum(d.bottles_delivered * 19)
      from public.customer_19l_deliveries d cross join latest l
      where d.created_at > l.measured_at
    ), 0)
    + coalesce((
      select sum(d.bottles_delivered * 19)
      from public.unassigned_19l_deliveries d cross join latest l
      where d.created_at > l.measured_at
    ), 0)
    + coalesce((
      select sum(private.mpw_counter_water_litres(
        c.sale_date, c.total_litres, c.counter_water_litres
      ))
      from public.counter_water_sales c cross join latest l
      where c.created_at > l.measured_at
    ), 0)
    + coalesce((
      select sum(p.quantity * 6)
      from public.production p cross join latest l
      where p.product_type = '6L' and p.created_at > l.measured_at
    ), 0) as outflow_litres
)
select
  l.id as measurement_id,
  l.measured_at,
  l.measured_litres,
  l.ledger_litres,
  l.variance_litres,
  f.inflow_litres,
  f.outflow_litres,
  l.measured_litres + f.inflow_litres - f.outflow_litres as current_balance_litres,
  l.measurement_method,
  l.note
from latest l cross join flows f;

grant select on public.shop_water_tank_current_balance to authenticated;

