create table if not exists public.unassigned_19l_deliveries (
  id bigint generated by default as identity primary key,
  delivery_date date not null default (now() at time zone 'Asia/Karachi')::date,
  worker_id bigint not null references public.workers(id),
  bottles_delivered integer not null check (bottles_delivered > 0),
  empty_bottles_returned integer not null default 0 check (empty_bottles_returned >= 0 and empty_bottles_returned <= bottles_delivered),
  labor_rate numeric not null default 20 check (labor_rate = 20),
  labor_amount numeric generated always as (bottles_delivered * labor_rate) stored,
  details text,
  request_id uuid not null unique,
  entered_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now()
);

create index if not exists unassigned_19l_deliveries_date_idx
  on public.unassigned_19l_deliveries(delivery_date);
create index if not exists unassigned_19l_deliveries_worker_date_idx
  on public.unassigned_19l_deliveries(worker_id, delivery_date);

alter table public.unassigned_19l_deliveries enable row level security;
drop policy if exists "Admins read unassigned 19L deliveries" on public.unassigned_19l_deliveries;
create policy "Admins read unassigned 19L deliveries"
  on public.unassigned_19l_deliveries for select to authenticated
  using (public.is_admin());

revoke insert, update, delete, truncate, references, trigger
  on public.unassigned_19l_deliveries from anon, authenticated;
grant select on public.unassigned_19l_deliveries to authenticated;
revoke all on sequence public.unassigned_19l_deliveries_id_seq from anon, authenticated;

drop trigger if exists unassigned_19l_closed_period_guard on public.unassigned_19l_deliveries;
create trigger unassigned_19l_closed_period_guard
before insert or update or delete on public.unassigned_19l_deliveries
for each row execute function private.mpw_guard_closed_period('delivery_date');

drop trigger if exists unassigned_19l_audit_trigger on public.unassigned_19l_deliveries;
create trigger unassigned_19l_audit_trigger
after insert or update or delete on public.unassigned_19l_deliveries
for each row execute function public.log_changes();

create or replace function public.record_unassigned_19l_delivery(
  p_delivery_date date,
  p_worker_id bigint,
  p_bottles_delivered integer,
  p_empty_bottles_returned integer default 0,
  p_details text default null,
  p_request_id uuid default null
) returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_existing public.unassigned_19l_deliveries%rowtype;
  v_id bigint;
  v_available numeric := 0;
  v_consumed numeric := 0;
  v_today date := (now() at time zone 'Asia/Karachi')::date;
  v_worker public.workers%rowtype;
begin
  if auth.uid() is null or not public.is_admin() then
    raise exception 'صرف مجاز ایڈمن یہ اندراج کر سکتا ہے۔' using errcode='42501';
  end if;
  if p_request_id is null then
    raise exception 'درخواست کی شناخت موجود نہیں۔' using errcode='22023';
  end if;
  if p_delivery_date is null or p_delivery_date > v_today then
    raise exception 'مستقبل کی تاریخ پر سپلائی درج نہیں ہو سکتی۔' using errcode='22023';
  end if;
  if p_bottles_delivered is null or p_bottles_delivered <= 0 then
    raise exception 'بوتلوں کی تعداد ایک یا زیادہ ہونی چاہیے۔' using errcode='22023';
  end if;
  if coalesce(p_empty_bottles_returned,0) < 0
     or coalesce(p_empty_bottles_returned,0) > p_bottles_delivered then
    raise exception 'واپس آنے والی خالی بوتلوں کی تعداد درست درج کریں۔' using errcode='22023';
  end if;

  select * into v_existing
  from public.unassigned_19l_deliveries
  where request_id = p_request_id;
  if found then
    if v_existing.delivery_date <> p_delivery_date
       or v_existing.worker_id <> p_worker_id
       or v_existing.bottles_delivered <> p_bottles_delivered
       or v_existing.empty_bottles_returned <> coalesce(p_empty_bottles_returned,0)
       or v_existing.details is distinct from nullif(btrim(p_details),'') then
      raise exception 'یہ درخواست پہلے مختلف تفصیل کے ساتھ محفوظ ہو چکی ہے۔' using errcode='23505';
    end if;
    return jsonb_build_object('id',v_existing.id,'worker_id',v_existing.worker_id,
      'bottles_delivered',v_existing.bottles_delivered,'labor_amount',v_existing.labor_amount,
      'already_saved',true);
  end if;

  select * into v_worker
  from public.workers
  where id=p_worker_id and is_active=true and is_owner=false
    and work_categories @> array['19L delivery']::text[];
  if not found then
    raise exception 'منتخب ورکر فعال نہیں یا 19L ڈیلیوری کے لیے مقرر نہیں۔' using errcode='22023';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('mpw-month-close-'||date_trunc('month',p_delivery_date)::date::text,0));
  if exists(select 1 from public.business_month_closings c
      where c.month_start=date_trunc('month',p_delivery_date)::date and c.status='closed') then
    raise exception 'یہ مہینہ بند ہو چکا ہے؛ اس تاریخ کا اندراج ممکن نہیں۔' using errcode='55000';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('water-pool-shop',0));
  select
    coalesce((select sum(tanker_count*1000) from public.water_tanker_purchases
      where water_use='shop_counter' and purchase_date<=p_delivery_date),0)
    + coalesce((select sum(litres) from public.water_opening_stock
      where water_use='shop_counter' and as_of_date<=p_delivery_date),0)
  into v_available;

  select
    coalesce((select sum(bottles_delivered*19) from public.customer_19l_deliveries
      where delivery_date<=p_delivery_date),0)
    + coalesce((select sum(total_litres) from public.counter_water_sales
      where sale_date<=p_delivery_date),0)
    + coalesce((select sum(quantity*6) from public.production
      where product_type='6L' and production_date<=p_delivery_date),0)
    + coalesce((select sum(bottles_delivered*19) from public.unassigned_19l_deliveries
      where delivery_date<=p_delivery_date),0)
  into v_consumed;

  if v_available-v_consumed < p_bottles_delivered*19 then
    raise exception 'دکان والی ٹنکی کا پانی ناکافی ہے۔ دستیاب لیٹر: %، درکار: %',
      greatest(v_available-v_consumed,0),p_bottles_delivered*19 using errcode='23514';
  end if;

  insert into public.unassigned_19l_deliveries(
    delivery_date,worker_id,bottles_delivered,empty_bottles_returned,details,request_id,entered_by
  ) values (
    p_delivery_date,p_worker_id,p_bottles_delivered,coalesce(p_empty_bottles_returned,0),
    nullif(btrim(p_details),''),p_request_id,auth.uid()
  ) returning id into v_id;

  insert into public.worker_ledger(
    worker_id,entry_date,entry_type,work_category,amount,note,source_table,source_id,entered_by,request_id
  ) values (
    p_worker_id,p_delivery_date,'earning','19L delivery',p_bottles_delivered*20,
    'غیر منسلک 19L سپلائی — '||p_bottles_delivered||' بوتلیں',
    'unassigned_19l_deliveries',v_id,auth.uid(),p_request_id
  );

  return jsonb_build_object('id',v_id,'worker_id',p_worker_id,
    'bottles_delivered',p_bottles_delivered,'labor_amount',p_bottles_delivered*20,
    'already_saved',false);
end;
$function$;

revoke all on function public.record_unassigned_19l_delivery(date,bigint,integer,integer,text,uuid) from public, anon;
grant execute on function public.record_unassigned_19l_delivery(date,bigint,integer,integer,text,uuid) to authenticated;
