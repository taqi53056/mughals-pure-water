CREATE VIEW public.store_credit_sale_balances
WITH (security_invoker=true)
AS
SELECT
  ps.id AS sale_id,
  ps.credit_store_id AS store_id,
  s.store_name,
  ps.sale_date,
  ps.product_type,
  ps.quantity,
  ps.unit,
  ps.total_amount,
  coalesce(sum(cp.amount),0)::numeric(14,2) AS amount_paid,
  greatest(ps.total_amount-coalesce(sum(cp.amount),0),0)::numeric(14,2) AS balance_due
FROM public.product_sales ps
JOIN public.business_stores s ON s.id=ps.credit_store_id
LEFT JOIN public.store_credit_payments cp ON cp.sale_id=ps.id
WHERE ps.payment_method='credit'
GROUP BY ps.id,s.id;

CREATE VIEW public.business_store_credit_balances
WITH (security_invoker=true)
AS
SELECT
  s.id AS store_id,
  s.store_name,
  s.mobile,
  s.address,
  s.is_active,
  s.credit_approved,
  coalesce(sum(b.balance_due),0)::numeric(14,2) AS balance_due
FROM public.business_stores s
LEFT JOIN public.store_credit_sale_balances b ON b.store_id=s.id
GROUP BY s.id;

