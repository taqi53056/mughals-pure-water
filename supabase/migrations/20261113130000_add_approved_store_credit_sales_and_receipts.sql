WHERE ps.payment_method='credit'
GROUP BY ps.id,s.id;

CREATE OR REPLACE VIEW public.business_store_credit_balances
WITH (security_invoker=true)
AS
SELECT
  s.id AS store_id,
  s.store_name,
  s.mobile,
  s.address,
  s.is_active,
  s.credit_approved,
  coalesce(sum(b.balance_due),0)::numeric(14,2) AS balance_due
FROM public.business_stores s
LEFT JOIN public.store_credit_sale_balances b ON b.store_id=s.id
GROUP BY s.id;

GRANT SELECT ON public.store_credit_sale_balances,public.business_store_credit_balances TO authenticated;
