CREATE OR REPLACE FUNCTION private.record_store_credit_payment(
  p_sale_id bigint,
  p_payment_date date,
  p_amount numeric,
  p_payment_method text,
  p_request_id uuid,
  p_details text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_existing public.store_credit_payments%rowtype;
  v_sale public.product_sales%rowtype;
  v_paid numeric(14,2);
  v_due numeric(14,2);
  v_payment_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'صرف ایڈمن ادھار وصولی درج کر سکتا ہے۔' USING ERRCODE='42501';
  END IF;
  IF p_request_id IS NULL OR p_sale_id IS NULL OR p_payment_date IS NULL
     OR p_amount IS NULL OR p_amount<=0 OR p_amount<>round(p_amount,2)
     OR p_payment_method NOT IN ('cash','bank','jazzcash','easypaisa','other')
     OR (p_details IS NOT NULL AND length(p_details)>300) THEN
    RAISE EXCEPTION 'ادھار وصولی کی تاریخ، مثبت رقم، طریقہ اور درخواست شناخت درست درج کریں۔' USING ERRCODE='22023';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-store-credit-request-'||p_request_id::text,0)
  );
  SELECT * INTO v_existing FROM public.store_credit_payments WHERE request_id=p_request_id;
  IF FOUND THEN
    IF v_existing.sale_id IS DISTINCT FROM p_sale_id
       OR v_existing.payment_date IS DISTINCT FROM p_payment_date
       OR v_existing.amount IS DISTINCT FROM p_amount
       OR v_existing.payment_method IS DISTINCT FROM p_payment_method
       OR v_existing.details IS DISTINCT FROM p_details THEN
      RAISE EXCEPTION 'درخواست کی شناخت پہلے مختلف وصولی کے لیے استعمال ہو چکی ہے۔' USING ERRCODE='23505';
    END IF;
    SELECT * INTO v_sale FROM public.product_sales WHERE id=v_existing.sale_id;
    SELECT coalesce(sum(amount),0) INTO v_paid FROM public.store_credit_payments WHERE sale_id=v_existing.sale_id;
    RETURN jsonb_build_object('payment_id',v_existing.id,'sale_id',v_existing.sale_id,
      'amount',v_existing.amount,'remaining_due',greatest(v_sale.total_amount-v_paid,0),
      'already_recorded',true);
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-month-close-'||date_trunc('month',p_payment_date)::date::text,0)
  );
  IF EXISTS (
    SELECT 1 FROM public.business_month_closings c
    WHERE c.month_start=date_trunc('month',p_payment_date)::date
  ) THEN
    RAISE EXCEPTION 'یہ مہینہ بند ہو چکا ہے؛ ادھار وصولی میں تبدیلی کی اجازت نہیں۔' USING ERRCODE='23514';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-store-credit-sale-'||p_sale_id::text,0)
  );
  SELECT * INTO v_sale FROM public.product_sales WHERE id=p_sale_id FOR UPDATE;
  IF NOT FOUND OR v_sale.payment_method<>'credit' OR v_sale.credit_store_id IS NULL THEN
    RAISE EXCEPTION 'منتخب سیل منظور شدہ دکان کی ادھار سیل نہیں۔' USING ERRCODE='23514';
  END IF;
  IF p_payment_date<v_sale.sale_date THEN
    RAISE EXCEPTION 'ادھار وصولی کی تاریخ سیل کی تاریخ سے پہلے نہیں ہو سکتی۔' USING ERRCODE='23514';
  END IF;

  SELECT coalesce(sum(amount),0) INTO v_paid
  FROM public.store_credit_payments WHERE sale_id=p_sale_id;
  v_due:=v_sale.total_amount-v_paid;
  IF p_amount>v_due THEN
    RAISE EXCEPTION 'وصولی بقایا سے زیادہ ہے۔ موجودہ بقایا: %',greatest(v_due,0) USING ERRCODE='23514';
  END IF;

  INSERT INTO public.store_credit_payments(
    sale_id,payment_date,amount,payment_method,details,request_id,entered_by
  )
  VALUES(p_sale_id,p_payment_date,p_amount,p_payment_method,nullif(btrim(p_details),''),p_request_id,auth.uid())
  RETURNING id INTO v_payment_id;

  RETURN jsonb_build_object(
    'payment_id',v_payment_id,'sale_id',p_sale_id,'amount',p_amount,
    'remaining_due',v_due-p_amount,'already_recorded',false
  );
END;
$function$;

