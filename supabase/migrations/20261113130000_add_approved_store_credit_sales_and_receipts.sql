
-- Approved-store credit sales. Cash remains the default; only explicitly approved stores may buy on credit.
CREATE TABLE public.business_stores (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  store_name text NOT NULL CHECK (length(btrim(store_name)) BETWEEN 2 AND 120),
  mobile text,
  address text,
  is_active boolean NOT NULL DEFAULT true,
  credit_approved boolean NOT NULL DEFAULT false,
  created_by uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_stores_mobile_length_check
    CHECK (mobile IS NULL OR length(btrim(mobile)) BETWEEN 7 AND 30)
);

ALTER TABLE public.product_sales
  ADD COLUMN credit_store_id bigint REFERENCES public.business_stores(id) ON DELETE RESTRICT;

ALTER TABLE public.product_sales
  DROP CONSTRAINT IF EXISTS product_sales_payment_method_check,
  ADD CONSTRAINT product_sales_payment_method_check
    CHECK (payment_method = ANY (ARRAY['cash','bank','jazzcash','easypaisa','other','credit'])),
  ADD CONSTRAINT product_sales_credit_store_required_check
    CHECK (
      (payment_method='credit' AND credit_store_id IS NOT NULL)
      OR (payment_method<>'credit' AND credit_store_id IS NULL)
    );

CREATE TABLE public.store_credit_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id bigint NOT NULL REFERENCES public.product_sales(id) ON DELETE RESTRICT,
  payment_date date NOT NULL,
  amount numeric(14,2) NOT NULL CHECK (amount>0),
  payment_method text NOT NULL CHECK (payment_method = ANY (ARRAY['cash','bank','jazzcash','easypaisa','other'])),
  details text,
  request_id uuid NOT NULL UNIQUE,
  entered_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT store_credit_payment_details_length_check
    CHECK (details IS NULL OR length(details)<=300)
);

CREATE INDEX business_stores_credit_approval_idx
  ON public.business_stores(is_active,credit_approved,store_name);
CREATE INDEX product_sales_credit_store_date_idx
  ON public.product_sales(credit_store_id,sale_date DESC)
  WHERE payment_method='credit';
CREATE INDEX store_credit_payments_sale_date_idx
  ON public.store_credit_payments(sale_id,payment_date,id);

ALTER TABLE public.business_stores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.store_credit_payments ENABLE ROW LEVEL SECURITY;

