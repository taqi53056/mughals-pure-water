CREATE OR REPLACE FUNCTION private.mpw_guard_credit_sale_store()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE v_approved boolean;
BEGIN
  IF NEW.payment_method='credit' THEN
    IF NEW.credit_store_id IS NULL THEN
      RAISE EXCEPTION 'ادھار سیل کے لیے منظور شدہ دکان منتخب کریں۔' USING ERRCODE='23514';
    END IF;
    SELECT (s.is_active AND s.credit_approved)
      INTO v_approved
    FROM public.business_stores s
    WHERE s.id=NEW.credit_store_id;
    IF NOT FOUND OR NOT coalesce(v_approved,false) THEN
      RAISE EXCEPTION 'یہ دکان فعال نہیں یا ادھار کے لیے منظور شدہ نہیں۔' USING ERRCODE='23514';
    END IF;
  ELSIF NEW.credit_store_id IS NOT NULL THEN
    RAISE EXCEPTION 'نقد/بینک سیل کے ساتھ ادھار دکان منسلک نہیں ہو سکتی۔' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$function$;

CREATE TRIGGER mpw_guard_credit_sale_store
BEFORE INSERT OR UPDATE OF payment_method,credit_store_id ON public.product_sales
FOR EACH ROW EXECUTE FUNCTION private.mpw_guard_credit_sale_store();

CREATE OR REPLACE FUNCTION private.record_product_sale_with_store_credit(
  p_sale_date date,
  p_product_type text,
  p_quantity integer,
  p_worker_id bigint,
  p_unit_price numeric,
  p_payment_method text,
  p_request_id uuid,
  p_credit_store_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_existing public.product_sales%rowtype;
  v_result jsonb;
  v_sale_id bigint;
  v_approved boolean;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'صرف ایڈمن سیل درج کر سکتا ہے۔' USING ERRCODE='42501';
  END IF;
  IF p_request_id IS NULL THEN
    RAISE EXCEPTION 'ہر سیل کے لیے منفرد درخواست شناخت لازمی ہے۔' USING ERRCODE='22023';
  END IF;
  IF p_payment_method NOT IN ('cash','bank','jazzcash','easypaisa','other','credit') THEN
    RAISE EXCEPTION 'ادائیگی کا طریقہ درست نہیں۔' USING ERRCODE='22023';
  END IF;

  IF p_payment_method<>'credit' THEN
    IF p_credit_store_id IS NOT NULL THEN
      RAISE EXCEPTION 'نقد سیل کے ساتھ ادھار دکان منتخب نہیں ہو سکتی۔' USING ERRCODE='22023';
    END IF;
    RETURN private.record_product_sale(
      p_sale_date,p_product_type,p_quantity,p_worker_id,p_unit_price,p_payment_method,p_request_id
    );
  END IF;

  IF p_credit_store_id IS NULL THEN
    RAISE EXCEPTION 'ادھار سیل کے لیے منظور شدہ دکان منتخب کریں۔' USING ERRCODE='22023';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-product-sale-request-'||p_request_id::text,0)
  );

  SELECT * INTO v_existing
  FROM public.product_sales
  WHERE request_id=p_request_id;

  IF FOUND THEN
    IF v_existing.sale_date IS DISTINCT FROM p_sale_date
       OR v_existing.product_type IS DISTINCT FROM p_product_type
       OR v_existing.quantity IS DISTINCT FROM p_quantity
       OR v_existing.worker_id IS DISTINCT FROM p_worker_id
       OR v_existing.unit_price IS DISTINCT FROM p_unit_price
       OR v_existing.payment_method IS DISTINCT FROM 'credit'
       OR v_existing.credit_store_id IS DISTINCT FROM p_credit_store_id THEN
      RAISE EXCEPTION 'درخواست کی شناخت پہلے مختلف سیل کے لیے استعمال ہو چکی ہے۔' USING ERRCODE='23505';
    END IF;
    RETURN jsonb_build_object(
      'sale_id',v_existing.id,'product_type',v_existing.product_type,
      'quantity',v_existing.quantity,'unit',v_existing.unit,
      'unit_price',v_existing.unit_price,'total_amount',v_existing.total_amount,
      'payment_method','credit','credit_store_id',v_existing.credit_store_id,
      'labor_amount',CASE WHEN v_existing.product_type='6L' OR v_existing.worker_id IS NULL
        OR coalesce((SELECT w.is_owner FROM public.workers w WHERE w.id=v_existing.worker_id),false)
        THEN 0 ELSE v_existing.quantity*10 END,
      'owner_saved_labor',CASE WHEN v_existing.product_type='6L' OR NOT
        coalesce((SELECT w.is_owner FROM public.workers w WHERE w.id=v_existing.worker_id),false)
        THEN 0 ELSE v_existing.quantity*10 END,
      'receivable_amount',v_existing.total_amount,
      'already_recorded',true
    );
  END IF;

  SELECT (s.is_active AND s.credit_approved)
    INTO v_approved
  FROM public.business_stores s
  WHERE s.id=p_credit_store_id;
  IF NOT FOUND OR NOT coalesce(v_approved,false) THEN
    RAISE EXCEPTION 'یہ دکان فعال نہیں یا ادھار کے لیے منظور شدہ نہیں۔' USING ERRCODE='23514';
  END IF;

  -- Reuse the existing sale stock, price, worker and idempotency guards;
  -- then atomically classify the sale as credit and attach the approved store.
  v_result:=private.record_product_sale(
    p_sale_date,p_product_type,p_quantity,p_worker_id,p_unit_price,'other',p_request_id
  );
  v_sale_id:=(v_result->>'sale_id')::bigint;

  UPDATE public.product_sales
  SET payment_method='credit',credit_store_id=p_credit_store_id
  WHERE id=v_sale_id
  RETURNING * INTO v_existing;

  RETURN jsonb_build_object(
    'sale_id',v_existing.id,'product_type',v_existing.product_type,
    'quantity',v_existing.quantity,'unit',v_existing.unit,
    'unit_price',v_existing.unit_price,'total_amount',v_existing.total_amount,
    'payment_method','credit','credit_store_id',v_existing.credit_store_id,
    'labor_amount',coalesce((v_result->>'labor_amount')::numeric,0),
    'owner_saved_labor',coalesce((v_result->>'owner_saved_labor')::numeric,0),
    'receivable_amount',v_existing.total_amount,
    'already_recorded',false
  );
END;
$function$;

