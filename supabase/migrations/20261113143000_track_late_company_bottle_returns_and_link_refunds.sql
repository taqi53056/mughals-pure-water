
-- Later-returned company 19L empties need their own custody movement.
-- A refundable Rs.1,600 deposit can only be refunded against a recorded return.
CREATE TABLE public.customer_19l_bottle_returns (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  return_date date NOT NULL,
  quantity integer NOT NULL CHECK(quantity>0),
  details text,
  request_id uuid NOT NULL UNIQUE,
  entered_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT customer_19l_bottle_returns_details_length CHECK(details IS NULL OR length(details)<=300)
);
CREATE INDEX customer_19l_bottle_returns_customer_date_idx
  ON public.customer_19l_bottle_returns(customer_id,return_date DESC,id);
CREATE INDEX customer_19l_bottle_returns_entered_by_idx
  ON public.customer_19l_bottle_returns(entered_by);

ALTER TABLE public.customer_19l_bottle_returns ENABLE ROW LEVEL SECURITY;
CREATE POLICY customer_19l_bottle_returns_admin_select
  ON public.customer_19l_bottle_returns FOR SELECT TO authenticated
  USING(public.is_admin());
GRANT SELECT ON public.customer_19l_bottle_returns TO authenticated;
REVOKE INSERT,UPDATE,DELETE ON public.customer_19l_bottle_returns FROM anon,authenticated;

CREATE TRIGGER customer_19l_bottle_returns_audit
AFTER INSERT OR UPDATE OR DELETE ON public.customer_19l_bottle_returns
FOR EACH ROW EXECUTE FUNCTION public.log_changes();
CREATE TRIGGER customer_19l_bottle_returns_no_future_date
BEFORE INSERT OR UPDATE ON public.customer_19l_bottle_returns
FOR EACH ROW EXECUTE FUNCTION private.mpw_guard_no_future_transaction_date('return_date');
CREATE TRIGGER customer_19l_bottle_returns_closed_period
BEFORE INSERT OR UPDATE OR DELETE ON public.customer_19l_bottle_returns
FOR EACH ROW EXECUTE FUNCTION private.mpw_guard_closed_period('return_date');

ALTER TABLE public.customer_bottle_deposit_ledger
  ADD COLUMN bottle_return_id bigint REFERENCES public.customer_19l_bottle_returns(id) ON DELETE RESTRICT;
ALTER TABLE public.customer_bottle_deposit_ledger
  ADD CONSTRAINT customer_bottle_deposit_return_link_check
  CHECK(
    (transaction_type='deposit_received' AND bottle_return_id IS NULL)
    OR (transaction_type='deposit_refunded' AND bottle_return_id IS NOT NULL)
  );
CREATE INDEX customer_bottle_deposit_return_id_idx
  ON public.customer_bottle_deposit_ledger(bottle_return_id)
  WHERE bottle_return_id IS NOT NULL;

CREATE OR REPLACE FUNCTION public.record_customer_19l_bottle_return(
  p_customer_id bigint,
  p_return_date date,
  p_quantity integer,
  p_request_id uuid,
  p_details text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_existing public.customer_19l_bottle_returns%rowtype;
  v_customer public.customers%rowtype;
  v_outstanding bigint;
  v_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'کمپنی کی خالی بوتل واپسی صرف ایڈمن درج کر سکتا ہے۔' USING ERRCODE='42501';
  END IF;
  IF p_customer_id IS NULL OR p_return_date IS NULL OR p_quantity IS NULL OR p_quantity<=0
     OR p_request_id IS NULL OR (p_details IS NOT NULL AND length(p_details)>300) THEN
    RAISE EXCEPTION 'کسٹمر، تاریخ، مثبت بوتل تعداد اور درخواست شناخت درست درج کریں۔' USING ERRCODE='22023';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('mpw-customer-bottle-return-request-'||p_request_id::text,0));
  SELECT * INTO v_existing FROM public.customer_19l_bottle_returns WHERE request_id=p_request_id;
  IF FOUND THEN
    IF v_existing.customer_id IS DISTINCT FROM p_customer_id
       OR v_existing.return_date IS DISTINCT FROM p_return_date
       OR v_existing.quantity IS DISTINCT FROM p_quantity
       OR v_existing.details IS DISTINCT FROM nullif(btrim(p_details),'') THEN
      RAISE EXCEPTION 'یہ درخواست پہلے مختلف بوتل واپسی کے لیے استعمال ہو چکی ہے۔' USING ERRCODE='23505';
    END IF;
    SELECT greatest(
      coalesce((SELECT sum(company_bottles_delivered-empty_bottles_returned)
        FROM public.customer_19l_deliveries WHERE customer_id=p_customer_id),0)
      -coalesce((SELECT sum(quantity) FROM public.customer_19l_bottle_returns WHERE customer_id=p_customer_id),0),0
    )::bigint INTO v_outstanding;
    RETURN jsonb_build_object('return_id',v_existing.id,'quantity',v_existing.quantity,
      'company_bottles_outstanding',v_outstanding,'already_recorded',true);
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('mpw-month-close-'||date_trunc('month',p_return_date)::date::text,0));
  IF EXISTS(SELECT 1 FROM public.business_month_closings
    WHERE month_start=date_trunc('month',p_return_date)::date AND status='closed') THEN
    RAISE EXCEPTION 'یہ مہینہ بند ہو چکا ہے؛ بوتل واپسی درج نہیں ہو سکتی۔' USING ERRCODE='55000';
  END IF;

  PERFORM pg_advisory_xact_lock(hashtextextended('mpw-customer-bottle-deposit-'||p_customer_id::text,0));
  SELECT * INTO v_customer FROM public.customers WHERE id=p_customer_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'منتخب کسٹمر موجود نہیں۔' USING ERRCODE='P0002'; END IF;

  SELECT greatest(
    coalesce((SELECT sum(company_bottles_delivered-empty_bottles_returned)
      FROM public.customer_19l_deliveries
      WHERE customer_id=p_customer_id AND delivery_date<=p_return_date),0)
    -coalesce((SELECT sum(quantity) FROM public.customer_19l_bottle_returns
      WHERE customer_id=p_customer_id AND return_date<=p_return_date),0),0
  )::bigint INTO v_outstanding;

  IF p_quantity>v_outstanding THEN
    RAISE EXCEPTION 'واپس کی جانے والی کمپنی بوتلیں موجودہ بقایا سے زیادہ ہیں۔ دستیاب: %',v_outstanding USING ERRCODE='23514';
  END IF;

  INSERT INTO public.customer_19l_bottle_returns(customer_id,return_date,quantity,details,request_id,entered_by)
  VALUES(p_customer_id,p_return_date,p_quantity,nullif(btrim(p_details),''),p_request_id,auth.uid())
  RETURNING id INTO v_id;

  RETURN jsonb_build_object('return_id',v_id,'quantity',p_quantity,
    'company_bottles_outstanding',v_outstanding-p_quantity,'already_recorded',false);
END;
$function$;

