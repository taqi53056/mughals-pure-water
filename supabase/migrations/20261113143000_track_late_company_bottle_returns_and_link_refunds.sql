CREATE OR REPLACE VIEW public.customer_bottle_deposit_balances
WITH(security_invoker=true)
AS
WITH deposits AS (
 SELECT customer_id,
  coalesce(sum(quantity) FILTER(WHERE transaction_type='deposit_received'),0)::bigint received_quantity,
  coalesce(sum(quantity) FILTER(WHERE transaction_type='deposit_refunded'),0)::bigint refunded_quantity,
  coalesce(sum(total_amount) FILTER(WHERE transaction_type='deposit_received'),0)::numeric(14,2) received_amount,
  coalesce(sum(total_amount) FILTER(WHERE transaction_type='deposit_refunded'),0)::numeric(14,2) refunded_amount
 FROM public.customer_bottle_deposit_ledger GROUP BY customer_id
), custody AS (
 SELECT d.customer_id,
  greatest(coalesce(sum(d.company_bottles_delivered),0)-coalesce(sum(d.empty_bottles_returned),0)
    -coalesce((SELECT sum(r.quantity) FROM public.customer_19l_bottle_returns r WHERE r.customer_id=d.customer_id),0),0)::bigint company_bottles_outstanding
 FROM public.customer_19l_deliveries d GROUP BY d.customer_id
)
SELECT c.id customer_id,c.customer_code,c.name,
 coalesce(cu.company_bottles_outstanding,0)::bigint company_bottles_outstanding,
 coalesce(d.received_quantity,0)::bigint deposit_received_quantity,
 coalesce(d.refunded_quantity,0)::bigint deposit_refunded_quantity,
 (coalesce(d.received_quantity,0)-coalesce(d.refunded_quantity,0))::bigint deposit_held_quantity,
 coalesce(d.received_amount,0)::numeric(14,2) deposit_received_amount,
 coalesce(d.refunded_amount,0)::numeric(14,2) deposit_refunded_amount,
 (coalesce(d.received_amount,0)-coalesce(d.refunded_amount,0))::numeric(14,2) deposit_held_amount
FROM public.customers c
LEFT JOIN deposits d ON d.customer_id=c.id
LEFT JOIN custody cu ON cu.customer_id=c.id;
GRANT SELECT ON public.customer_bottle_deposit_balances TO authenticated;

CREATE OR REPLACE VIEW public.customer_19l_bottle_return_balances
WITH(security_invoker=true)
AS
SELECT r.id return_id,r.customer_id,r.return_date,r.quantity,
 coalesce(sum(l.quantity),0)::integer refunded_quantity,
 greatest(r.quantity-coalesce(sum(l.quantity),0),0)::integer available_for_refund,
 r.details
FROM public.customer_19l_bottle_returns r
LEFT JOIN public.customer_bottle_deposit_ledger l
 ON l.bottle_return_id=r.id AND l.transaction_type='deposit_refunded'
GROUP BY r.id,r.customer_id,r.return_date,r.quantity,r.details;
GRANT SELECT ON public.customer_19l_bottle_return_balances TO authenticated;

-- Extend the chronological custody guard so future delivery edits cannot invalidate late returns.
CREATE OR REPLACE FUNCTION public.guard_customer_19l_bottle_custody()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO ''
AS $function$
DECLARE v_customer_id bigint; v_negative_date date;
BEGIN
 IF TG_OP='UPDATE' AND NEW.customer_id IS DISTINCT FROM OLD.customer_id THEN
  RAISE EXCEPTION 'محفوظ ڈلیوری کو دوسرے گاہک کے اکاؤنٹ میں منتقل نہیں کیا جا سکتا۔' USING ERRCODE='22023';
 END IF;
 v_customer_id:=NEW.customer_id;
 PERFORM pg_advisory_xact_lock(hashtextextended('mpw-customer-bottle-deposit-'||v_customer_id::text,0));
 WITH movements AS (
  SELECT d.delivery_date movement_date,
    sum(d.bottles_delivered-d.customer_owned_bottles)::bigint company_in,
    sum(d.empty_bottles_returned)::bigint company_out
  FROM public.customer_19l_deliveries d
  WHERE d.customer_id=v_customer_id AND (TG_OP<>'UPDATE' OR d.id IS DISTINCT FROM OLD.id)
  GROUP BY d.delivery_date
  UNION ALL
  SELECT NEW.delivery_date,NEW.bottles_delivered-NEW.customer_owned_bottles,NEW.empty_bottles_returned
  UNION ALL
  SELECT r.return_date,0,r.quantity
  FROM public.customer_19l_bottle_returns r WHERE r.customer_id=v_customer_id
 ), daily AS (
  SELECT movement_date,sum(company_in) company_in,sum(company_out) company_out
  FROM movements GROUP BY movement_date
 ), running AS (
  SELECT movement_date,sum(company_in-company_out) OVER(ORDER BY movement_date
    ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) outstanding FROM daily
 )
 SELECT movement_date INTO v_negative_date FROM running WHERE outstanding<0 ORDER BY movement_date LIMIT 1;
 IF v_negative_date IS NOT NULL THEN
  RAISE EXCEPTION 'کمپنی کی واپس آنے والی خالی بوتلیں، پہلے دی گئی کمپنی بوتلوں سے زیادہ ہیں۔ تاریخ: %',v_negative_date USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END;
$function$;

