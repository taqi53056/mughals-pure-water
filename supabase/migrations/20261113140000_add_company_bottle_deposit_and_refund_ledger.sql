
-- Admin-only, separate refundable deposit ledger for company-owned 19L bottles.
-- Rs.1,600 per bottle; never posts automatically to a customer's monthly water bill.
ALTER TABLE public.customer_archive_summaries
  ADD COLUMN IF NOT EXISTS company_bottles_outstanding bigint NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bottle_deposit_received numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bottle_deposit_refunded numeric(14,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS bottle_deposit_held numeric(14,2) NOT NULL DEFAULT 0;

CREATE TABLE public.customer_bottle_deposit_ledger (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  transaction_date date NOT NULL,
  transaction_type text NOT NULL CHECK (transaction_type IN ('deposit_received','deposit_refunded')),
  quantity integer NOT NULL CHECK (quantity>0),
  unit_amount numeric(12,2) NOT NULL DEFAULT 1600 CHECK (unit_amount=1600),
  total_amount numeric(14,2) GENERATED ALWAYS AS (quantity::numeric*unit_amount) STORED,
  payment_method text NOT NULL CHECK (payment_method IN ('cash','bank','jazzcash','easypaisa','other')),
  bottle_return_confirmed boolean NOT NULL DEFAULT false,
  details text,
  request_id uuid NOT NULL UNIQUE,
  entered_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT customer_bottle_deposit_confirmation_check
    CHECK (
      (transaction_type='deposit_received' AND bottle_return_confirmed=false)
      OR (transaction_type='deposit_refunded' AND bottle_return_confirmed=true)
    ),
  CONSTRAINT customer_bottle_deposit_details_length_check
    CHECK (details IS NULL OR length(details)<=300)
);

CREATE INDEX customer_bottle_deposit_customer_date_idx
  ON public.customer_bottle_deposit_ledger(customer_id,transaction_date DESC,id);
CREATE INDEX customer_bottle_deposit_entered_by_idx
  ON public.customer_bottle_deposit_ledger(entered_by);

ALTER TABLE public.customer_bottle_deposit_ledger ENABLE ROW LEVEL SECURITY;
