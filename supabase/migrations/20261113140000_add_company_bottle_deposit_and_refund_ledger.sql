CREATE VIEW public.customer_bottle_deposit_balances
WITH (security_invoker=true)
AS
WITH deposits AS (
  SELECT customer_id,
    coalesce(sum(quantity) FILTER(WHERE transaction_type='deposit_received'),0)::bigint AS received_quantity,
    coalesce(sum(quantity) FILTER(WHERE transaction_type='deposit_refunded'),0)::bigint AS refunded_quantity,
    coalesce(sum(total_amount) FILTER(WHERE transaction_type='deposit_received'),0)::numeric(14,2) AS received_amount,
    coalesce(sum(total_amount) FILTER(WHERE transaction_type='deposit_refunded'),0)::numeric(14,2) AS refunded_amount
  FROM public.customer_bottle_deposit_ledger
  GROUP BY customer_id
), custody AS (
  SELECT customer_id,
    greatest(coalesce(sum(company_bottles_delivered),0)-coalesce(sum(empty_bottles_returned),0),0)::bigint AS company_bottles_outstanding
  FROM public.customer_19l_deliveries
  GROUP BY customer_id
)
SELECT c.id AS customer_id,c.customer_code,c.name,
  coalesce(cu.company_bottles_outstanding,0)::bigint AS company_bottles_outstanding,
  coalesce(d.received_quantity,0)::bigint AS deposit_received_quantity,
  coalesce(d.refunded_quantity,0)::bigint AS deposit_refunded_quantity,
  (coalesce(d.received_quantity,0)-coalesce(d.refunded_quantity,0))::bigint AS deposit_held_quantity,
  coalesce(d.received_amount,0)::numeric(14,2) AS deposit_received_amount,
  coalesce(d.refunded_amount,0)::numeric(14,2) AS deposit_refunded_amount,
  (coalesce(d.received_amount,0)-coalesce(d.refunded_amount,0))::numeric(14,2) AS deposit_held_amount
FROM public.customers c
LEFT JOIN deposits d ON d.customer_id=c.id
LEFT JOIN custody cu ON cu.customer_id=c.id;

GRANT SELECT ON public.customer_bottle_deposit_balances TO authenticated;

CREATE OR REPLACE FUNCTION private.record_customer_bottle_deposit(
  p_customer_id bigint,
  p_transaction_date date,
  p_transaction_type text,
  p_quantity integer,
  p_payment_method text,
  p_request_id uuid,
  p_details text,
  p_bottle_return_confirmed boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_existing public.customer_bottle_deposit_ledger%rowtype;
  v_customer public.customers%rowtype;
  v_outstanding bigint;
  v_held_quantity bigint;
  v_held_amount numeric(14,2);
  v_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT public.is_admin() THEN
    RAISE EXCEPTION 'کمپنی بوتل کی ضمانت/واپسی صرف ایڈمن درج کر سکتا ہے۔' USING ERRCODE='42501';
  END IF;
  IF p_customer_id IS NULL OR p_transaction_date IS NULL
     OR p_transaction_type NOT IN ('deposit_received','deposit_refunded')
     OR p_quantity IS NULL OR p_quantity<=0
     OR p_payment_method NOT IN ('cash','bank','jazzcash','easypaisa','other')
     OR p_request_id IS NULL
     OR p_bottle_return_confirmed IS NULL
     OR (p_details IS NOT NULL AND length(p_details)>300) THEN
    RAISE EXCEPTION 'کسٹمر، تاریخ، قسم، مثبت بوتل مقدار، ادائیگی طریقہ اور درخواست شناخت درست درج کریں۔' USING ERRCODE='22023';
  END IF;
  IF (p_transaction_type='deposit_received' AND p_bottle_return_confirmed)
     OR (p_transaction_type='deposit_refunded' AND NOT p_bottle_return_confirmed) THEN
    RAISE EXCEPTION 'ضمانت کی واپسی صرف کمپنی کی بوتل حقیقتاً واپس ملنے کی ایڈمن تصدیق کے بعد درج ہو سکتی ہے۔' USING ERRCODE='23514';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-customer-bottle-deposit-request-'||p_request_id::text,0)
  );
  SELECT * INTO v_existing
  FROM public.customer_bottle_deposit_ledger
  WHERE request_id=p_request_id;
  IF FOUND THEN
    IF v_existing.customer_id IS DISTINCT FROM p_customer_id
       OR v_existing.transaction_date IS DISTINCT FROM p_transaction_date
       OR v_existing.transaction_type IS DISTINCT FROM p_transaction_type
       OR v_existing.quantity IS DISTINCT FROM p_quantity
       OR v_existing.payment_method IS DISTINCT FROM p_payment_method
       OR v_existing.details IS DISTINCT FROM nullif(btrim(p_details),'')
       OR v_existing.bottle_return_confirmed IS DISTINCT FROM p_bottle_return_confirmed THEN
      RAISE EXCEPTION 'درخواست کی شناخت پہلے مختلف ضمانت/واپسی کے لیے استعمال ہو چکی ہے۔' USING ERRCODE='23505';
    END IF;
    SELECT coalesce(sum(CASE WHEN transaction_type='deposit_received' THEN quantity ELSE -quantity END),0),
           coalesce(sum(CASE WHEN transaction_type='deposit_received' THEN total_amount ELSE -total_amount END),0)
      INTO v_held_quantity,v_held_amount
    FROM public.customer_bottle_deposit_ledger
    WHERE customer_id=p_customer_id;
    RETURN jsonb_build_object('ledger_id',v_existing.id,'transaction_type',v_existing.transaction_type,
      'quantity',v_existing.quantity,'total_amount',v_existing.total_amount,
      'held_quantity',v_held_quantity,'held_amount',v_held_amount,'already_recorded',true);
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-month-close-'||date_trunc('month',p_transaction_date)::date::text,0)
  );
  IF EXISTS (
    SELECT 1 FROM public.business_month_closings c
    WHERE c.month_start=date_trunc('month',p_transaction_date)::date AND c.status='closed'
  ) THEN
    RAISE EXCEPTION 'یہ مہینہ بند ہو چکا ہے؛ بوتل ضمانت کے اندراج میں تبدیلی کی اجازت نہیں۔' USING ERRCODE='23514';
  END IF;

  PERFORM pg_advisory_xact_lock(
    hashtextextended('mpw-customer-bottle-deposit-'||p_customer_id::text,0)
  );
  SELECT * INTO v_customer FROM public.customers WHERE id=p_customer_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'منتخب کسٹمر موجود نہیں۔' USING ERRCODE='P0002';
  END IF;

  SELECT greatest(coalesce(sum(company_bottles_delivered),0)-coalesce(sum(empty_bottles_returned),0),0)::bigint
    INTO v_outstanding
  FROM public.customer_19l_deliveries
  WHERE customer_id=p_customer_id;

  SELECT coalesce(sum(CASE WHEN transaction_type='deposit_received' THEN quantity ELSE -quantity END),0),
         coalesce(sum(CASE WHEN transaction_type='deposit_received' THEN total_amount ELSE -total_amount END),0)
    INTO v_held_quantity,v_held_amount
  FROM public.customer_bottle_deposit_ledger
  WHERE customer_id=p_customer_id;

  IF p_transaction_type='deposit_received' THEN
    IF p_quantity>greatest(v_outstanding-v_held_quantity,0) THEN
      RAISE EXCEPTION 'ضمانت صرف موجودہ غیر واپس شدہ کمپنی بوتلوں کے لیے لی جا سکتی ہے۔ دستیاب بوتلیں: %',
        greatest(v_outstanding-v_held_quantity,0) USING ERRCODE='23514';
    END IF;
  ELSE
    IF p_quantity>greatest(v_held_quantity,0) THEN
      RAISE EXCEPTION 'واپس کی جانے والی ضمانت موجودہ جمع شدہ ضمانت سے زیادہ ہے۔ دستیاب بوتلیں: %',
        greatest(v_held_quantity,0) USING ERRCODE='23514';
    END IF;
  END IF;

  INSERT INTO public.customer_bottle_deposit_ledger(
    customer_id,transaction_date,transaction_type,quantity,unit_amount,
    payment_method,bottle_return_confirmed,details,request_id,entered_by
  )
  VALUES(
    p_customer_id,p_transaction_date,p_transaction_type,p_quantity,1600,
    p_payment_method,p_bottle_return_confirmed,nullif(btrim(p_details),''),p_request_id,auth.uid()
  )
  RETURNING id INTO v_id;

  IF p_transaction_type='deposit_received' THEN
    v_held_quantity:=v_held_quantity+p_quantity;
    v_held_amount:=v_held_amount+(p_quantity*1600);
  ELSE
    v_held_quantity:=v_held_quantity-p_quantity;
    v_held_amount:=v_held_amount-(p_quantity*1600);
  END IF;

  RETURN jsonb_build_object(
    'ledger_id',v_id,'transaction_type',p_transaction_type,'quantity',p_quantity,
    'total_amount',p_quantity*1600,'held_quantity',v_held_quantity,
    'held_amount',v_held_amount,'already_recorded',false
  );
END;
$function$;

